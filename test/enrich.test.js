import { test } from 'node:test';
import assert from 'node:assert/strict';
import { articleText, videoIdOf, applyTranscript } from '../src/enrich.js';
import { mapLinkedinPost } from '../src/collectors.js';

test('articleText keeps the article body and drops the page around it', () => {
  const html = `<html><body><nav><p>Home About Contact Subscribe to our newsletter today please</p></nav>
  <header><p>Breaking: site header text that is long enough to count as a paragraph</p></header>
  <article><h2>Vertical farms find their footing</h2>
  <p>Indoor growers are cutting energy costs by moving to newer LED fixtures across their farms.</p>
  <script>var x = "<p>not text, a script that should never appear in the output</p>";</script>
  <p>Short.</p>
  <li>Containers now ship with sensors that report pH and moisture every minute.</li>
  <p>Indoor growers are cutting energy costs by moving to newer LED fixtures across their farms.</p>
  </article><footer><p>Copyright notice that is long enough to be a paragraph on its own</p></footer></body></html>`;
  const t = articleText(html);
  assert.match(t, /Vertical farms find their footing/);
  assert.match(t, /LED fixtures/);
  assert.match(t, /pH and moisture/);
  assert.doesNotMatch(t, /newsletter|header text|Copyright|script/);
  assert.equal(t.split('LED fixtures').length, 2, 'a repeated paragraph is kept once');
  assert.doesNotMatch(t, /Short\./);
});

test('articleText falls back to <main>, then the body', () => {
  assert.match(articleText('<main><p>The main part of the page holds the real story about hydroponics.</p></main>'), /hydroponics/);
  assert.match(articleText('<body><p>Only a body here, but it still carries a full sentence of text.</p></body>'), /full sentence/);
  assert.equal(articleText(''), '');
});

test('videoIdOf reads the id from the feed guid or the link', () => {
  assert.equal(videoIdOf({ guid: 'yt:video:dQw4w9WgXcQ' }), 'dQw4w9WgXcQ');
  assert.equal(videoIdOf({ guid: 'x', url: 'https://www.youtube.com/watch?v=jNQXAC9IVRw' }), 'jNQXAC9IVRw');
  assert.equal(videoIdOf({ guid: 'x', url: 'https://www.youtube.com/shorts/9bZkp7q19f0' }), '9bZkp7q19f0');
  assert.equal(videoIdOf({ guid: 'x', url: 'https://example.com' }), null);
});

test('applyTranscript puts what was said after the description, with the video details', () => {
  const it = { guid: 'yt:video:dQw4w9WgXcQ', content: 'feed description' };
  applyTranscript(it, { videoId: 'dQw4w9WgXcQ', description: 'Full description', fullText: 'Hello  growers,\n today we test pumps.', viewCount: 1200, durationSeconds: 300, keywords: ['hydroponics'], selectedLanguage: 'en', isAutoGenerated: true, channelName: 'Grow' });
  assert.equal(it.content, 'Full description\n\nTranscript:\nHello growers, today we test pumps.');
  assert.equal(it.meta.capture, 'transcript');
  assert.equal(it.meta.views, 1200);
  assert.equal(it.meta.duration_s, 300);
  assert.deepEqual(it.meta.keywords, ['hydroponics']);

  const none = { guid: 'yt:video:jNQXAC9IVRw', content: 'feed description' };
  applyTranscript(none, { videoId: 'jNQXAC9IVRw', segments: [] });
  assert.equal(none.content, 'feed description');
  assert.equal(none.meta.capture, 'description');
  assert.equal(none.meta.transcript_note, 'the video has no captions');

  const segs = { guid: 'yt:video:9bZkp7q19f0' };
  applyTranscript(segs, { videoId: '9bZkp7q19f0', segments: [{ text: 'one' }, { text: 'two' }] });
  assert.match(segs.content, /Transcript:\none two$/);
});

test('mapLinkedinPost keeps a shared post and the post details', () => {
  const p = mapLinkedinPost({
    urn: 'urn:li:activity:1',
    url: 'https://www.linkedin.com/posts/x',
    text: 'My take on this',
    author: { first_name: 'Henry', last_name: 'Gordon-Smith' },
    posted_at: { timestamp: 1794700000000 },
    stats: { total_reactions: 16 },
    reshared_post: { text: 'Data centers dump heat. Greenhouses buy heat.', author: { first_name: 'Ann', last_name: 'Lee' }, url: 'https://l/2' },
  });
  assert.match(p.content, /^My take on this\n\nShared post by Ann Lee:\nData centers dump heat/);
  assert.deepEqual(p.meta.stats, { total_reactions: 16 });
  assert.equal(p.meta.reshared.author, 'Ann Lee');
  const plain = mapLinkedinPost({ urn: 'u2', text: 'Just a post' });
  assert.equal(plain.content, 'Just a post');
  assert.equal(plain.meta.reshared, null);
});
